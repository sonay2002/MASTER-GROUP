const fs = require('fs');
const path = require('path');
const root = process.cwd();
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const prefs = fs.readFileSync(path.join(root, 'js/settings-preferences-v450.js'), 'utf8');
const docs = fs.readFileSync(path.join(root, 'js/document-actions-v419.js'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
const core = fs.readFileSync(path.join(root, 'js/estimate-core.js'), 'utf8');
const assert = (ok, msg) => { if (!ok) throw new Error(msg); };
assert(html.includes('id="mgAppLanguage"') && html.includes('id="mgDocumentLanguage"'), 'both language selectors must exist');
assert(html.includes('data-settings-hub="preferences"'), 'preferences must be inside existing Settings hub');
assert(html.includes('settings-preferences-v450.js?v=451'), 'v450 preferences runtime must be loaded');
assert(prefs.includes("localStorage.setItem") && prefs.includes("mg_app_language_v1") && prefs.includes("mg_document_language_v1"), 'language choices must persist');
assert(prefs.includes('MutationObserver') && prefs.includes('translateAll'), 'dynamic interface must be translated after rerender');
assert(prefs.includes('scanDarkTree') && prefs.includes('restoreDarkOverrides') && prefs.includes('background-image'), 'dark theme must recolor and restore generated/inline surfaces');
assert(prefs.includes('getDocumentLanguage') && prefs.includes('tDoc'), 'document language API must be exported');
assert(docs.includes("dt('КЛИЕНТ')") && docs.includes("dt('ИТОГО:')") && docs.includes('getDocumentLanguage'), 'image/PDF export labels must use document language');
assert(core.includes("dt('Клиент')") && core.includes("dt('Телефон')") && core.includes("dt('ИТОГО:')"), 'shared estimate text must use document language');
assert(sw.includes('master-group-v451') && sw.includes('settings-preferences-v450.js?v=451') && sw.includes('soft-graphite-theme-v451.css?v=451'), 'service worker must cache current preferences runtime and graphite theme');
assert(html.includes('soft-graphite-theme-v451.css?v=451'), 'graphite theme stylesheet must be loaded');
console.log('Settings language/theme v450 smoke test passed');
