#!/usr/bin/env node
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const finance=fs.readFileSync(path.join(root,'js','finance-ui.js'),'utf8');
const templates=fs.readFileSync(path.join(root,'js','estimate-templates.js'),'utf8');
const css=fs.readFileSync(path.join(root,'css','styles.css'),'utf8');
const actions=fs.readFileSync(path.join(root,'js','document-actions-v419.js'),'utf8');
if((finance.match(/function v58Document\(/g)||[]).length!==1) throw new Error('Document renderer count mismatch');
if(!finance.includes('window.MGEstimateTemplates?.get?.()')) throw new Error('Settings selection is not authoritative');
if(!finance.includes('data-rendered-template="${currentTemplate}"')) throw new Error('Rendered selection marker missing');
if(!finance.includes("const grouped=currentTemplate==='template2'")) throw new Error('Sectioned template route missing');
if(!finance.includes('colspan="6"')) throw new Error('Section heading must span six columns');
if(!finance.includes('Подытог раздела')) throw new Error('Per-section subtotal missing');
if(!templates.includes("const allowed=['template1','template2']")) throw new Error('Allowed template IDs mismatch');
if(!templates.includes("'template6':'template2'")) throw new Error('Old stored template choices are not normalized');
if(!index.includes('id="estimateTemplateList" class="estimate-template-list"></div>')) throw new Error('Template list host missing');
if(!css.includes('.tpl-template2 .tpl-section-row th')) throw new Error('Section template styling missing');
if(!actions.includes('async function printEstimate()')||!actions.includes('application/pdf')||!actions.includes('pngToPdf(image)')) throw new Error('PDF export action missing');
if(index.includes('estimateTemplateDots')||templates.includes('data-template-dot')) throw new Error('Template pagination dots must be removed');
console.log('estimate-template-routing-two-smoke: OK');
