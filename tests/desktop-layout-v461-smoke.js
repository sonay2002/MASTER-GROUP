'use strict';
const fs = require('fs');
const html = fs.readFileSync('index.html', 'utf8');
const css = fs.readFileSync('css/desktop-layout-v463.css', 'utf8');
const sw = fs.readFileSync('sw.js', 'utf8');
const manifest = fs.readFileSync('manifest.webmanifest', 'utf8');
if (!html.includes('css/desktop-layout-v463.css?v=463')) throw new Error('Desktop layout stylesheet is not linked');
if (!html.includes('<meta name="app-version" content="v463">')) throw new Error('App version was not bumped');
if (!html.includes('id="mgDesktopEstimatesHeading"') || !html.includes('data-action="new"')) throw new Error('Desktop estimates heading/action is missing');
if (!sw.includes("master-group-v463-desktop-layout-fix") || !sw.includes('./css/desktop-layout-v463.css?v=463')) throw new Error('Service Worker does not cache the desktop layout update');
if (!css.includes('@media screen and (min-width:1100px)')) throw new Error('Desktop styling is not behind a wide-screen breakpoint');
if (!css.includes('width:calc(100% - 250px)!important')) throw new Error('Main workspace does not account for the persistent sidebar');
if (!css.includes('#estimatesScreen:not(.mge-editing) .status-filter-card')) throw new Error('Desktop estimate filters are not scoped to list mode');
if (!manifest.includes('\"orientation\": \"any\"')) throw new Error('Installed app remains locked to portrait orientation');
if (!css.includes('.mge-estimates-desktop-table') || !css.includes('display:block!important')) throw new Error('Full-width estimate table rules missing');
console.log('v463 desktop layout / full-width estimates / focused editor: PASS');
