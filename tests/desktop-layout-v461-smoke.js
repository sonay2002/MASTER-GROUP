'use strict';
const fs = require('fs');
const html = fs.readFileSync('index.html', 'utf8');
const css = fs.readFileSync('css/desktop-layout-v462.css', 'utf8');
const sw = fs.readFileSync('sw.js', 'utf8');
const manifest = fs.readFileSync('manifest.webmanifest', 'utf8');
if (!html.includes('css/desktop-layout-v462.css?v=462')) throw new Error('Desktop layout stylesheet is not linked');
if (!html.includes('<meta name="app-version" content="v462">')) throw new Error('App version was not bumped');
if (!html.includes('id="mgDesktopEstimatesHeading"') || !html.includes('data-action="new"')) throw new Error('Desktop estimates heading/action is missing');
if (!sw.includes("master-group-v462-desktop-workspace") || !sw.includes('./css/desktop-layout-v462.css?v=462')) throw new Error('Service Worker does not cache the desktop layout update');
if (!css.includes('@media screen and (min-width: 1100px)')) throw new Error('Desktop styling is not behind a wide-screen breakpoint');
if (!css.includes('width: calc(100% - 248px) !important')) throw new Error('Main workspace does not account for the persistent sidebar');
if (!css.includes('body:has(#estimatesScreen:not([hidden]))')) throw new Error('Active navigation state not tied to the current screen');
if (!manifest.includes('\"orientation\": \"any\"')) throw new Error('Installed app remains locked to portrait orientation');
if (!css.includes('.mge-estimates-desktop-table') || !css.includes('min-width: 1300px')) throw new Error('Wide estimate table breakpoint missing');
console.log('v462 desktop workspace / mobile scope / estimates table: PASS');
