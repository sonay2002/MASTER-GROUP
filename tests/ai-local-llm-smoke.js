const fs=require('fs'),vm=require('vm');
const source=fs.readFileSync('js/mg-ai-service.js','utf8');
const context={window:{MGCatalog:{data:[]}},console,setTimeout,clearTimeout,JSON,String,Number,Map,Object,Array,Error,Set,Math,Promise};
context.window.window=context.window;
vm.createContext(context);vm.runInContext(source,context);
if(context.window.MG_AI_SERVICE.version!=='v417-local-ai-router-qwen-gemma-deepseek') throw new Error('Version mismatch');
const st=context.window.MG_AI_SERVICE.getStatus();
if(st.remoteInference!==false||st.remoteApi!==false||st.remoteHost!==false) throw new Error('AI must not use remote inference/API');
const models=Array.isArray(st.model)?st.model:[];
for(const required of ['onnx-community/Qwen3.5-2B-ONNX-OPT','onnx-community/gemma-3-1b-it-ONNX','onnx-community/DeepSeek-R1-Distill-Qwen-1.5B-ONNX']) if(!models.includes(required)) throw new Error('Missing local brain: '+required);
if(st.brainOrder!=='brains-first-then-10m-memory') throw new Error('Wrong stage order');
if(st.localInference!==true) throw new Error('Local inference flag missing');
if(st.firstRunNeedsNetwork!==true) throw new Error('First-run network flag missing');
console.log('AI local LLM integration smoke: OK');
