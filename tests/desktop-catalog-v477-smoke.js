const fs = require('fs');
const assert = require('assert');
const html = fs.readFileSync('index.html', 'utf8');
const sw = fs.readFileSync('sw.js', 'utf8');
const css = fs.readFileSync('css/desktop-catalog-v477.css', 'utf8');
const js = fs.readFileSync('js/desktop-catalog-v477.js', 'utf8');
assert.ok(html.includes('css/desktop-catalog-v477.css?v=477') && html.includes('js/desktop-catalog-v477.js?v=477'), 'index.html must load the v477 files');
assert.ok(sw.includes('./css/desktop-catalog-v477.css?v=477') && sw.includes('./js/desktop-catalog-v477.js?v=477'), 'Service Worker must precache the v477 files');
assert.ok(/min-width:1100px/.test(css) && !/@media[^{]*max-width/.test(css), 'catalog css must be desktop-only');
assert.ok(js.includes("matchMedia('(min-width:1100px)"), 'catalog js must be gated by the desktop media query');
assert.ok(!/localStorage|MGStorage|persist\(/.test(js), 'catalog nav must never read or write storage');
assert.ok(js.includes('data-mg-cat-off') && /data-mg-cat-off\]/.test(css), 'unselected directions are hidden by attribute only');
console.log('v477 desktop catalog smoke test passed');
